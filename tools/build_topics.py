"""Build the topic pages - one subject of the site at an address of its own.

Why (Yossi, 28.11): the site is one page, and every subject in it opens as a
panel at "#kosher", "#skipass" and so on. A search engine drops everything
after the "#", so to Google the whole site is one address, the home page, and
somebody searching "kosher food in Cervinia" is never shown it. A topic page
is that one subject as plain text at a real address (/kosher/, /en/kosher/),
with a door into the full site.

The pages are made from texts.json and texts.en.json - the same content the
panels show - so there is nothing to keep in step by hand. Do not edit the
generated files: .github/workflows/build-topics.yml rewrites them on every
push that changes the texts or this script.

    python3 tools/build_topics.py          # writes the pages
    python3 tools/build_topics.py --check  # fails if a page is out of date
"""
