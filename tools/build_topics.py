def overlay(base, en):
    """texts.en.json over texts.json, by the same rule as _overlayTexts in
    index.html: objects by key, arrays by "id" where the items carry one,
    else by position; what is not translated stays as it was."""
    if en is None:
        return base
    if isinstance(base, list) and isinstance(en, list):
        ids = bool(en) and all(isinstance(x, dict) and x.get('id') is not None for x in en)
        by_id = {x['id']: x for x in en} if ids else {}
        out = []
        for i, b in enumerate(base):
            if ids:
                out.append(overlay(b, by_id[b['id']]) if isinstance(b, dict) and b.get('id') in by_id else b)
            else:
                out.append(overlay(b, en[i]) if i < len(en) else b)
        return out
    if isinstance(base, dict) and isinstance(en, dict):
        o = dict(base)
        for k, v in en.items():
            o[k] = overlay(base[k], v) if k in base else v
        return o
    return en


def load():
    he = json.loads((ROOT / 'texts.json').read_text(encoding='utf-8'))
    en_raw = json.loads((ROOT / 'texts.en.json').read_text(encoding='utf-8'))
    return {'he': he, 'en': overlay(he, en_raw)}


def attr(s):
    return html.escape(s, quote=True)


def plain(s):
    """Text for a <title> or a description: no tags, no leading symbols."""
    s = re.sub(r'<[^>]+>', '', s or '')
    return html.unescape(s).strip()


def unmark(s):
    """A heading from the texts without the emoji it leads with."""
    return re.sub(r'^[^A-Za-z0-9֐-׿"\'(]+', '', s or '').strip()


def ltr_split(line):
    """"<ltr>" is the author's own mark in a product line: what comes before
    it is the heading, what follows is a run of Latin brand names."""
    if '<ltr>' not in line:
        return line
    head, tail = line.split('<ltr>', 1)
    head = re.sub(r'(?:\s|&nbsp;)*(?:—|:)?(?:\s|&nbsp;)*$', '', head)
    return (('<span class="ph">' + head + '</span>') if head else '') + \
        '<span class="brands" dir="ltr">' + tail.replace('<ltr>', ' ') + '</span>'


def place_cards(places, city, lang):
    out = []
    for p in places or []:
        links = []
        if p.get('url'):
            links.append('<a href="%s" target="_blank" rel="noopener">%s</a>'
                         % (attr(p['url']), 'Website' if lang == 'en' else 'אתר'))
        q = p.get('map') or (unmark(p.get('name', '')) + (', ' + p['addr'] if p.get('addr') else '') + ', ' + city)
        from urllib.parse import quote
        links.append('<a href="https://www.google.com/maps/search/?api=1&amp;query=%s" target="_blank" rel="noopener">%s</a>'
                     % (quote(p.get('latlon') or q), 'Map' if lang == 'en' else 'מפה'))
        out.append(
            '<div class="card"><h4>%s</h4>' % p.get('name', '')
            + ('<p class="addr"><bdi dir="ltr">%s</bdi></p>' % p['addr'] if p.get('addr') else '')
            + ('<p>%s</p>' % p['desc'] if p.get('desc') else '')
            + ('<p class="ksh">%s</p>' % p['kashrut'] if p.get('kashrut') else '')
            + ('<p class="tel"><a href="tel:%s" dir="ltr">%s</a></p>'
               % (re.sub(r'[^+0-9]', '', p['phone']), p['phone']) if p.get('phone') else '')
            + '<p class="links">' + ' · '.join(links) + '</p>'
            + ('<p class="warn">%s</p>' % p['warn'] if p.get('warn') else '')
            + '</div>')
    return '\n'.join(out)


def kosher_body(ko, lang, today):
    T = (lambda he, en: en) if lang == 'en' else (lambda he, en: he)
    b = []
    add = b.append

    add('<h2>%s</h2>' % unmark(ko['cervinia_title']))
    add('<p>%s</p>' % ko['cervinia_text'])

    g = ko.get('cervinia_group') or {}
    if g.get('text'):
        past = bool(g.get('until')) and g['until'] < today
        add('<h3>%s</h3>' % unmark(g.get('title', '')))
        add('<p>%s</p>' % ((past and g.get('text_after')) or g['text']))

    add('<h2>%s</h2>' % unmark(ko['cervinia_products_title']))
    in_list = False
    for ln in ko.get('cervinia_products', []):
        if str(ln).startswith('##'):
            if in_list:
                add('</ul>')
            add('<h3>%s</h3>' % ln[2:].strip())
            add('<ul class="prod">')
            in_list = True
        elif in_list:
            add('<li>%s</li>' % ltr_split(ln))
        else:
            add('<p>%s</p>' % ltr_split(ln))
    if in_list:
        add('</ul>')

    if ko.get('cervinia_tips'):
        add('<h2>%s</h2>' % unmark(ko['cervinia_tips_title']))
        add('<ul>' + ''.join('<li>%s</li>' % t for t in ko['cervinia_tips']) + '</ul>')

    add('<h2>%s</h2>' % unmark(ko['delivery_title']))
    add('<p>%s</p>' % ko['delivery_desc'])
    add('<p>%s</p>' % ko['delivery_tip'])

    add('<h2>%s</h2>' % T('אוכל כשר במילאנו (Milano), בדרך לצ\'רוויניה', 'Kosher food in Milan, on the way to Cervinia'))
    add('<p>%s</p>' % ko['milan_note'])
    add('<h3>%s</h3>' % unmark(ko['milan_restaurants_title']))
    add(place_cards(ko.get('milan_places'), 'Milano', lang))
    add('<p class="src">%s</p>' % ko['milan_restaurants_footer'])
    add('<p>%s</p>' % ko['milan_shopping_tip'])
    add('<h3>%s</h3>' % unmark(ko['milan_shuls_title']))
    add('<p>%s</p>' % ko['milan_shuls_note'])
    add(place_cards(ko.get('milan_shuls'), 'Milano', lang))
    add('<h3>%s</h3>' % unmark(ko['milan_stays_title']))
    add('<p>%s</p>' % ko['milan_stays_note'])
    add(place_cards(ko.get('milan_stays'), 'Milano', lang))

    add('<h2>%s</h2>' % T('אוכל כשר בטורינו (Torino)', 'Kosher food in Turin'))
    add('<p>%s</p>' % ko['torino_note'])
    add(place_cards(ko.get('torino_places'), 'Torino', lang))
    add('<p>%s</p>' % ko['torino_restaurants_footer'])
    add('<p>%s</p>' % ko['torino_tip'])

    if ko.get('mikveh_text'):
        add('<h2>%s</h2>' % unmark(ko['mikveh_title']))
        add('<p>%s</p>' % ko['mikveh_text'])
    return '\n'.join(b)


