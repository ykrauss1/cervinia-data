def outputs(today):
    texts = load()
    out = {}
    for slug in TOPICS:
        out[ROOT / slug / 'index.html'] = page(slug, 'he', texts, today)
        out[ROOT / 'en' / slug / 'index.html'] = page(slug, 'en', texts, today)
    return out


def main():
    check = '--check' in sys.argv
    today = datetime.date.today().isoformat()
    stale = []
    for path, text in outputs(today).items():
        if check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')
        print('wrote', path.relative_to(ROOT), len(text.encode('utf-8')), 'bytes')
    if stale:
        sys.exit('build_topics: out of date: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
