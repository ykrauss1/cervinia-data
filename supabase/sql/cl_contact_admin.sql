-- ======================================================================
--  CerviniaLive - the contact form's messages, read and answered on the site
--
--  The contact form already writes every message to public.contact_messages
--  (besides sending the mail). This lets the admin read them on the site,
--  mark them handled and keep the answer he sent (control panel -> 📬).
--
--  Visitors keep exactly one right: to leave a new message. Reading,
--  changing and deleting belong to profiles marked is_admin, and nobody
--  else - not the public key, not a signed-in visitor.
--
--  Run once in Supabase -> SQL Editor. Safe to run twice.
-- ======================================================================

-- what happened to a message, and what was answered
alter table public.contact_messages
  add column if not exists id         bigint generated by default as identity,
  add column if not exists status     text not null default 'new',
  add column if not exists reply      text,
  add column if not exists replied_at timestamptz;

alter table public.contact_messages drop constraint if exists contact_messages_status_ok;
alter table public.contact_messages add constraint contact_messages_status_ok
  check (status in ('new', 'done', 'replied'));

-- the rights: nothing by default, then only what each one needs
alter table public.contact_messages enable row level security;
revoke all on public.contact_messages from anon, authenticated;
grant insert (name, email, subject, message, created_at) on public.contact_messages to anon, authenticated;
grant select, update, delete on public.contact_messages to authenticated;

-- the policies this table had before are replaced by these
do $$
declare p record;
begin
  for p in select policyname from pg_policies
           where schemaname = 'public' and tablename = 'contact_messages'
  loop
    execute format('drop policy %I on public.contact_messages', p.policyname);
  end loop;
end $$;

-- anyone may leave a message - a new one, with no answer in it
create policy contact_insert on public.contact_messages
  for insert to anon, authenticated
  with check (status = 'new' and reply is null and replied_at is null);

-- only an admin reads, changes and deletes
create policy contact_admin_select on public.contact_messages
  for select to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin = true));

create policy contact_admin_update on public.contact_messages
  for update to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin = true))
  with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin = true));

create policy contact_admin_delete on public.contact_messages
  for delete to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin = true));
