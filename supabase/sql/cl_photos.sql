-- ======================================================================
--  CerviniaLive - photos that skiers upload, shown only once approved
--
--  A signed-in visitor uploads a photo of Cervinia ("היכרות עם צ'רוויניה"
--  -> 📸). It waits, seen by nobody but him and the admin, until the admin
--  approves it in the control panel (📷). Only then does anyone else see it.
--
--  The files sit in a private bucket, cl-photos. Nobody gets a file by its
--  address alone: a reader asks for a signed address, and storage grants it
--  only for a photo whose row says approved (or to its owner, or the admin).
--
--  Run once in Supabase -> SQL Editor. Safe to run twice.
-- ======================================================================

-- the photos ----------------------------------------------------------
create table if not exists public.cl_photos (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  path        text not null unique,              -- <user id>/<random>.jpg in cl-photos
  caption     text,
  show_name   boolean not null default true,     -- show the uploader's username beside it
  status      text not null default 'new',
  created_at  timestamptz not null default now(),
  reviewed_at timestamptz,
  constraint cl_photos_status_ok  check (status in ('new', 'approved', 'rejected')),
  constraint cl_photos_caption_ok check (caption is null or char_length(caption) <= 140),
  constraint cl_photos_path_ok    check (path ~ '^[0-9a-f-]{36}/[A-Za-z0-9_-]{8,40}\.jpg$')
);
create index if not exists cl_photos_status_idx on public.cl_photos (status, created_at desc);

-- is the caller an admin (profiles.is_admin)
create or replace function public.cl_is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin = true);
$$;
-- anon too: the read policies below ask it (and it answers false for anon)
revoke all on function public.cl_is_admin() from public;
grant execute on function public.cl_is_admin() to anon, authenticated;

-- the rights: nothing by default, then only what each one needs
alter table public.cl_photos enable row level security;
revoke all on public.cl_photos from anon, authenticated;
grant select on public.cl_photos to anon, authenticated;
grant insert (path, caption, show_name) on public.cl_photos to authenticated;
grant update (status, reviewed_at) on public.cl_photos to authenticated;
grant delete on public.cl_photos to authenticated;

do $$
declare p record;
begin
  for p in select policyname from pg_policies
           where schemaname = 'public' and tablename = 'cl_photos'
  loop
    execute format('drop policy %I on public.cl_photos', p.policyname);
  end loop;
end $$;

-- everyone sees approved photos; the uploader his own; the admin all
create policy cl_photos_select on public.cl_photos
  for select to anon, authenticated
  using (status = 'approved' or user_id = auth.uid() or public.cl_is_admin());

-- a signed-in visitor adds his own photo, waiting, under his own folder,
-- and no more than ten waiting at a time
create policy cl_photos_insert on public.cl_photos
  for insert to authenticated
  with check (
    user_id = auth.uid()
    and status = 'new' and reviewed_at is null
    and split_part(path, '/', 1) = auth.uid()::text
    and (select count(*) from public.cl_photos q
         where q.user_id = auth.uid() and q.status = 'new') < 10
  );

-- only the admin approves or rejects
create policy cl_photos_update on public.cl_photos
  for update to authenticated
  using (public.cl_is_admin())
  with check (public.cl_is_admin());

-- the uploader may take his photo away; the admin may remove any
create policy cl_photos_delete on public.cl_photos
  for delete to authenticated
  using (user_id = auth.uid() or public.cl_is_admin());

-- the approved photos with the uploader's name where he allowed it.
-- profiles is not opened for this: the function returns the name only.
create or replace function public.cl_photos_public(p_limit int default 60)
returns table (id bigint, path text, caption text, name text, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select ph.id, ph.path, ph.caption,
         case when ph.show_name then pr.username end,
         ph.created_at
  from public.cl_photos ph
  left join public.profiles pr on pr.id = ph.user_id
  where ph.status = 'approved'
  order by ph.reviewed_at desc nulls last, ph.id desc
  limit least(greatest(coalesce(p_limit, 60), 1), 200);
$$;
revoke all on function public.cl_photos_public(int) from public;
grant execute on function public.cl_photos_public(int) to anon, authenticated;

-- the admin's list: waiting ones first, with who sent them
create or replace function public.cl_photos_admin(p_status text default 'new')
returns table (id bigint, path text, caption text, show_name boolean, status text,
               name text, created_at timestamptz)
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.cl_is_admin() then raise exception 'not allowed'; end if;
  return query
    select ph.id, ph.path, ph.caption, ph.show_name, ph.status, pr.username, ph.created_at
    from public.cl_photos ph
    left join public.profiles pr on pr.id = ph.user_id
    where p_status is null or ph.status = p_status
    order by ph.created_at desc
    limit 200;
end $$;
revoke all on function public.cl_photos_admin(text) from public, anon;
grant execute on function public.cl_photos_admin(text) to authenticated;

-- the bucket: private, JPEG only (the site shrinks every photo to a JPEG
-- before it is sent), up to 3 MB ---------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('cl-photos', 'cl-photos', false, 3145728, array['image/jpeg'])
on conflict (id) do update
  set public = false, file_size_limit = 3145728, allowed_mime_types = array['image/jpeg'];

drop policy if exists cl_photos_obj_insert on storage.objects;
drop policy if exists cl_photos_obj_select on storage.objects;
drop policy if exists cl_photos_obj_delete on storage.objects;

-- a signed-in visitor uploads only into his own folder
create policy cl_photos_obj_insert on storage.objects
  for insert to authenticated
  with check (bucket_id = 'cl-photos' and (storage.foldername(name))[1] = auth.uid()::text);

-- a file may be read (a signed address made for it) only when its row is
-- approved, or by its owner, or by the admin
create policy cl_photos_obj_select on storage.objects
  for select to anon, authenticated
  using (
    bucket_id = 'cl-photos' and (
      exists (select 1 from public.cl_photos ph where ph.path = storage.objects.name and ph.status = 'approved')
      or (storage.foldername(name))[1] = auth.uid()::text
      or public.cl_is_admin()
    )
  );

-- the owner or the admin removes a file
create policy cl_photos_obj_delete on storage.objects
  for delete to authenticated
  using (bucket_id = 'cl-photos' and ((storage.foldername(name))[1] = auth.uid()::text or public.cl_is_admin()));
